// Writes src/js/pumpPhotos.js: the pump photos (from dealer-page/img/pumps) as data URIs, for the
// Products page in the app. Run after tools/build_pump_photos.py:  node tools/build_app_photos.js
// The section and photo rules themselves are in src/js/pumpCatalog.js (kept in step with the dealer page).
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'dealer-page', 'img', 'pumps');
const photos = {};
fs.readdirSync(dir).filter(f => f.endsWith('.webp')).sort().forEach(f => {
  photos[f.replace(/\.webp$/, '')] = 'data:image/webp;base64,' + fs.readFileSync(path.join(dir, f)).toString('base64');
});
const out = '// Generated by tools/build_app_photos.js. Do not edit by hand.\nconst PUMP_PHOTOS = ' + JSON.stringify(photos) + ';\n';
fs.writeFileSync(path.join(root, 'src', 'js', 'pumpPhotos.js'), out);
console.log(`src/js/pumpPhotos.js written: ${(out.length / 1024).toFixed(0)} KB, ${Object.keys(photos).length} photos`);
